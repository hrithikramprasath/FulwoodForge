"""IETF RFC 9457 Problem Details for HTTP APIs (`application/problem+json`).

Leaf schema module (REQ-API-01): ZERO upward imports.
"""

from __future__ import annotations

from typing import Any

from pydantic import AliasChoices, BaseModel, ConfigDict, Field

PROBLEM_JSON_MEDIA_TYPE = "application/problem+json"


class InvalidParam(BaseModel):
    """Field-level validation error detail for RFC 9457 422 responses."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(
        description="Field path or parameter name that failed validation."
    )
    reason: str = Field(
        description="Human-readable explanation of the validation failure."
    )


class ProblemDetails(BaseModel):
    """Canonical IETF RFC 9457 Problem Details payload."""

    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    type: str = Field(
        default="about:blank",
        description="URI reference identifying the problem type.",
    )
    title: str = Field(description="Short, human-readable summary of the problem type.")
    status: int = Field(
        ge=400,
        le=599,
        description="HTTP status code generated by the origin server.",
    )
    detail: str = Field(
        description="Human-readable explanation specific to this occurrence of the problem."
    )
    instance: str = Field(
        description="URI reference identifying the specific occurrence of the problem."
    )
    invalid_params: list[InvalidParam] | None = Field(
        default=None,
        validation_alias=AliasChoices("invalid_params", "invalid-params"),
        serialization_alias="invalid-params",
        description="Optional list of field validation errors for 400/422 responses.",
    )
    request_id: str | None = Field(
        default=None,
        description="Correlation UUIDv7 for dual-plane audit and log lookup.",
    )


def build_problem_details(
    *,
    status: int,
    title: str,
    detail: str,
    instance: str,
    problem_type: str = "about:blank",
    invalid_params: list[InvalidParam] | None = None,
    request_id: str | None = None,
) -> dict[str, Any]:
    """Construct and serialize an RFC 9457 ProblemDetails dictionary with hyphenated aliases."""
    problem = ProblemDetails(
        type=problem_type,
        title=title,
        status=status,
        detail=detail,
        instance=instance,
        invalid_params=invalid_params,
        request_id=request_id,
    )
    return problem.model_dump(by_alias=True, exclude_none=True)
